using System;
using System.IO;
using System.Linq;
using System.Text.Json;

return regressionTests.run();

internal static class regressionTests
{
    private static int assertions;
    private static int passedSuites;
    private static JsonDocument reference;

    public static int run()
    {
        reference = JsonDocument.Parse(File.ReadAllText(Path.Combine(AppContext.BaseDirectory, "iso226-2023-reference.json")));
        try
        {
            runSuite("Independent 29-node, 40/60/80-phon goldens", goldenContours);
            runSuite("Exact 1 kHz reference and uncapped relative gains", referenceAndRelativeGains);
            runSuite("Log-frequency interpolation and knot continuity", interpolationAndContinuity);
            runSuite("Independent inverse oracle and level monotonicity", inverseAndMonotonicity);
            runSuite("Interior peak controls fixed-domain normalization", interiorMaximum);
            runSuite("Gain bounds and ratios across full supported domain", boundsAndRatios);
            runSuite("Fixed profile query-order and master-volume invariance", profileInvariance);
            runSuite("Negative corrections, external reference and singleton domains", specialDomains);
            runSuite("Invalid/nonfinite arguments and profile bounds", invalidInputs);
            runSuite("Internal construction cannot bypass validation", constructorValidation);
            Console.WriteLine("PASS: " + passedSuites + " suites, " + assertions + " assertions.");
            return 0;
        }
        catch (Exception exception)
        {
            Console.Error.WriteLine("FAIL after " + assertions + " assertions: " + exception);
            return 1;
        }
        finally
        {
            reference.Dispose();
        }
    }

    private static void runSuite(string name, Action test)
    {
        test();
        passedSuites++;
        Console.WriteLine("PASS " + name);
    }

    private static void goldenContours()
    {
        JsonElement rows = reference.RootElement.GetProperty("derivedReferenceValues");
        assertTrue(rows.GetArrayLength() == 29, "Reference must contain all 29 ISO nodes.");
        double previousFrequency = 0;
        foreach (JsonElement row in rows.EnumerateArray())
        {
            double frequency = row.GetProperty("frequencyHz").GetDouble();
            assertTrue(frequency > previousFrequency, "Golden frequencies strictly increase.");
            previousFrequency = frequency;
            foreach (int phon in new[] { 40, 60, 80 })
                near(pianoLoudnessCompensation.getSoundPressureLevelDb(frequency, phon),
                    row.GetProperty("phon" + phon).GetDouble(), 1e-9, "Independent golden");
        }

        // These independent numbers also guard against accidentally replacing the
        // reference file with values generated by the implementation under test.
        near(pianoLoudnessCompensation.getSoundPressureLevelDb(20, 60), 109.36806643681697, 1e-9, "20 Hz");
        near(pianoLoudnessCompensation.getSoundPressureLevelDb(100, 60), 78.50401616215893, 1e-9, "100 Hz");
        near(pianoLoudnessCompensation.getSoundPressureLevelDb(3150, 40), 35.4656495515826, 1e-6, "3150 Hz");
        near(pianoLoudnessCompensation.getSoundPressureLevelDb(12500, 60), 68.57716757095461, 1e-9, "12.5 kHz");
    }

    private static void referenceAndRelativeGains()
    {
        for (double phon = 20; phon <= 80; phon += 0.25)
        {
            near(pianoLoudnessCompensation.getSoundPressureLevelDb(1000, phon), phon, 1e-11, "1 kHz SPL");
            near(pianoLoudnessCompensation.getRelativeGain(1000, phon), 1, 1e-13, "1 kHz relative gain");
        }
        near(pianoLoudnessCompensation.getRelativeGain(20, 60), 294.0379064020272, 1e-9, "No arbitrary gain cap");
        near(pianoLoudnessCompensation.getRelativeGain(100, 60), 8.417842739987623, 1e-11, "Amplitude uses /20");
        near(pianoLoudnessCompensation.getRelativeGain(3150, 60), 0.6577874752776108, 1e-12, "Attenuation allowed");
        near(pianoLoudnessCompensation.getRelativeGain(250, 60, 250), 1, 1e-13, "Non-1 kHz self-reference");
        double expected = Math.Pow(10, (golden(100, 60) - golden(250, 60)) / 20);
        near(pianoLoudnessCompensation.getRelativeGain(100, 60, 250), expected, 1e-12, "Non-1 kHz ratio");
    }

    private static void interpolationAndContinuity()
    {
        JsonElement[] rows = reference.RootElement.GetProperty("derivedReferenceValues").EnumerateArray().ToArray();
        for (int i = 1; i < rows.Length; i++)
        {
            double low = rows[i - 1].GetProperty("frequencyHz").GetDouble();
            double high = rows[i].GetProperty("frequencyHz").GetDouble();
            foreach (int phon in new[] { 40, 60, 80 })
            {
                foreach (double fraction in new[] { 0.25, 0.5, 0.75 })
                {
                    double frequency = low * Math.Pow(high / low, fraction);
                    double expected = (1 - fraction) * rows[i - 1].GetProperty("phon" + phon).GetDouble()
                        + fraction * rows[i].GetProperty("phon" + phon).GetDouble();
                    near(pianoLoudnessCompensation.getSoundPressureLevelDb(frequency, phon),
                        expected, 1e-10, "Log-frequency interpolation");
                }
                if (i < rows.Length - 1)
                {
                    double node = rows[i].GetProperty("phon" + phon).GetDouble();
                    near(pianoLoudnessCompensation.getSoundPressureLevelDb(high * (1 - 1e-10), phon),
                        node, 1e-7, "Left continuity");
                    near(pianoLoudnessCompensation.getSoundPressureLevelDb(high * (1 + 1e-10), phon),
                        node, 1e-7, "Right continuity");
                }
            }
        }
    }

    private static void inverseAndMonotonicity()
    {
        JsonElement data = reference.RootElement;
        JsonElement frequencies = data.GetProperty("frequenciesHz");
        for (int i = 0; i < 29; i++)
        {
            double frequency = frequencies[i].GetDouble();
            double alpha = data.GetProperty("alpha")[i].GetDouble();
            double transferDb = data.GetProperty("transferLevelDb")[i].GetDouble();
            double thresholdDb = data.GetProperty("hearingThresholdDb")[i].GetDouble();
            double previousSpl = double.NegativeInfinity;
            for (int phon = 20; phon <= 80; phon++)
            {
                double spl = pianoLoudnessCompensation.getSoundPressureLevelDb(frequency, phon);
                assertTrue(spl > previousSpl, "SPL increases with phon.");
                previousSpl = spl;
                // Independent inverse form, with coefficients supplied by the
                // separately transcribed standards reference, not production fields.
                double recoveredPhon = 100.0 / 3.0 * Math.Log10(
                    (Math.Pow(10, alpha * (spl + transferDb) / 10)
                    - Math.Pow(10, alpha * (thresholdDb + transferDb) / 10))
                    / Math.Pow(4e-10, 0.3 - alpha) + Math.Pow(10, 0.072));
                near(recoveredPhon, phon, 1e-10, "Independent inverse");
            }
        }
    }

    private static void interiorMaximum()
    {
        var profile = pianoLoudnessCompensation.createNormalizedGainProfile(1250, 2000, 60);
        // The maximum is at 1600 Hz, not at either domain endpoint.
        near(profile.normalizationDb, golden(1600, 60) - 60, 1e-10, "Interior maximum");
        near(profile.getNormalizedGain(1600), 1, 1e-12, "Interior maximum maps to unity");
        near(profile.getNormalizedGain(1250), 0.880592797054, 1e-10, "Lower endpoint normalized");
        near(profile.getNormalizedGain(2000), 0.689431110299, 1e-10, "Upper endpoint normalized");

        var partialSegment = pianoLoudnessCompensation.createNormalizedGainProfile(1400, 1900, 60);
        near(partialSegment.normalizationDb, golden(1600, 60) - 60, 1e-10, "Non-node domain endpoints");
        near(partialSegment.getNormalizedGain(1600), 1, 1e-12, "Interior node retained");
    }

    private static void boundsAndRatios()
    {
        foreach (int phon in new[] { 20, 40, 60, 80 })
        {
            var profile = pianoLoudnessCompensation.createNormalizedGainProfile(20, 12500, phon);
            for (int i = 0; i <= 500; i++)
            {
                double frequency = i == 500 ? 12500 : 20 * Math.Pow(12500.0 / 20, i / 500.0);
                double gain = profile.getNormalizedGain(frequency, 0.8);
                assertTrue(!double.IsNaN(gain) && !double.IsInfinity(gain) && gain > 0 && gain <= 0.8 + 1e-13,
                    "Every gain remains finite and inside the shared bound.");
            }
            near(profile.getNormalizedGain(20, 0.8), 0.8, 1e-12, "Full-domain maximum");
        }

        var sixty = pianoLoudnessCompensation.createNormalizedGainProfile(20, 12500, 60);
        near(sixty.getNormalizedGain(1000), 0.0034009220519776685, 1e-13, "Full-domain 1 kHz normalization");
        double[] notes = { 100, 250, 500, 1000, 3150, 8000, 12500 };
        foreach (double first in notes)
        foreach (double second in notes)
        {
            double gainDbDifference = 20 * Math.Log10(
                sixty.getNormalizedGain(first, 0.7) / sixty.getNormalizedGain(second, 0.7));
            near(gainDbDifference, golden(first, 60) - golden(second, 60), 1e-9,
                "Independent pairwise contour differences preserved");
        }
    }

    private static void profileInvariance()
    {
        var profile = pianoLoudnessCompensation.createNormalizedGainProfile(100, 8000, 60);
        double[] notes = { 100, 250, 500, 1000, 3150, 8000 };
        double[] firstPass = notes.Select(note => profile.getNormalizedGain(note, 0.8)).ToArray();
        for (int i = notes.Length - 1; i >= 0; i--)
        {
            near(profile.getNormalizedGain(notes[i], 0.8), firstPass[i], 0, "Query-order independence");
            near(profile.getNormalizedGain(notes[i], 0.2), firstPass[i] * 0.25, 1e-14, "One common master multiplier");
            near(profile.getNormalizedGain(notes[i], 0), 0, 0, "Zero master");
            near(pianoLoudnessCompensation.getNormalizedGain(notes[i], profile, 0.8),
                firstPass[i], 0, "Static convenience helper");
        }

        var differentReference = pianoLoudnessCompensation.createNormalizedGainProfile(100, 8000, 60, 250);
        foreach (double note in notes)
            near(differentReference.getNormalizedGain(note), profile.getNormalizedGain(note), 1e-12,
                "Reference cancels when both normalization corrections are positive");
    }

    private static void specialDomains()
    {
        var negative = pianoLoudnessCompensation.createNormalizedGainProfile(3000, 3500, 60);
        near(negative.normalizationDb, 0, 0, "Negative corrections do not cause a boost");
        near(negative.getNormalizedGain(3150), 0.6577874752776108, 1e-12, "No minimum gain floor");

        var singletonBoost = pianoLoudnessCompensation.createNormalizedGainProfile(100, 100, 60);
        near(singletonBoost.getNormalizedGain(100), 1, 1e-12, "Singleton boosted domain");
        var singletonCut = pianoLoudnessCompensation.createNormalizedGainProfile(3150, 3150, 60);
        near(singletonCut.getNormalizedGain(3150), 0.6577874752776108, 1e-12, "Singleton attenuation domain");

        var boundary = pianoLoudnessCompensation.createNormalizedGainProfile(20, 12500, 80, 12500);
        assertTrue(boundary.getNormalizedGain(20) <= 1, "Upper supported phon and reference frequency accepted.");
        near(boundary.minFrequencyHz, 20, 0, "Stored minimum");
        near(boundary.maxFrequencyHz, 12500, 0, "Stored maximum");
        near(boundary.loudnessLevelPhon, 80, 0, "Stored phon");
        near(boundary.referenceFrequencyHz, 12500, 0, "Stored reference");
    }

    private static void invalidInputs()
    {
        double[] invalidFrequencies = { double.NaN, double.PositiveInfinity, double.NegativeInfinity, -1, 0, 19.999, 12500.001 };
        foreach (double invalid in invalidFrequencies)
        {
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.getSoundPressureLevelDb(invalid, 60));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.getRelativeGain(invalid, 60));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.getRelativeGain(1000, 60, invalid));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.createNormalizedGainProfile(invalid, 12500, 60));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.createNormalizedGainProfile(20, invalid, 60));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.createNormalizedGainProfile(20, 12500, 60, invalid));
        }

        double[] invalidPhons = { double.NaN, double.PositiveInfinity, double.NegativeInfinity, 0, 19.999, 80.001, 90 };
        foreach (double invalid in invalidPhons)
        {
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.getSoundPressureLevelDb(1000, invalid));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.getRelativeGain(1000, invalid));
            throws<ArgumentOutOfRangeException>(() => pianoLoudnessCompensation.createNormalizedGainProfile(20, 12500, invalid));
        }

        throws<ArgumentException>(() => pianoLoudnessCompensation.createNormalizedGainProfile(2000, 1000, 60));
        throws<ArgumentNullException>(() => pianoLoudnessCompensation.getNormalizedGain(1000, null, 0.5));

        var profile = pianoLoudnessCompensation.createNormalizedGainProfile(100, 4000, 60);
        foreach (double invalid in invalidFrequencies.Concat(new[] { 50.0, 5000.0 }))
        {
            throws<ArgumentOutOfRangeException>(() => profile.getNormalizedGain(invalid));
            throws<ArgumentOutOfRangeException>(() => profile.getNormalizedGain(invalid, 0));
        }
        foreach (double invalid in new[] { double.NaN, double.PositiveInfinity, double.NegativeInfinity, -0.0001, 1.0001 })
            throws<ArgumentOutOfRangeException>(() => profile.getNormalizedGain(1000, invalid));
    }

    private static void constructorValidation()
    {
        throws<ArgumentOutOfRangeException>(() => new pianoLoudnessCompensation.normalizedGainProfile(0, 1000, 60, 1000));
        throws<ArgumentOutOfRangeException>(() => new pianoLoudnessCompensation.normalizedGainProfile(20, 12500, double.NaN, 1000));
        throws<ArgumentException>(() => new pianoLoudnessCompensation.normalizedGainProfile(2000, 1000, 60, 1000));
        var valid = new pianoLoudnessCompensation.normalizedGainProfile(1250, 2000, 60, 1000);
        near(valid.getNormalizedGain(1600), 1, 1e-12, "Internal construction computes valid normalization");
    }

    private static double golden(double frequencyHz, int phon)
    {
        foreach (JsonElement row in reference.RootElement.GetProperty("derivedReferenceValues").EnumerateArray())
            if (row.GetProperty("frequencyHz").GetDouble() == frequencyHz)
                return row.GetProperty("phon" + phon).GetDouble();
        throw new InvalidOperationException("Missing golden frequency " + frequencyHz);
    }

    private static void near(double actual, double expected, double tolerance, string context)
    {
        assertions++;
        if (double.IsNaN(actual) || double.IsInfinity(actual) || Math.Abs(actual - expected) > tolerance)
            throw new InvalidOperationException(context + ": expected " + expected.ToString("R")
                + ", actual " + actual.ToString("R") + ", tolerance " + tolerance);
    }

    private static void assertTrue(bool condition, string context)
    {
        assertions++;
        if (!condition)
            throw new InvalidOperationException(context);
    }

    private static void throws<exceptionType>(Action action) where exceptionType : Exception
    {
        assertions++;
        try { action(); }
        catch (exceptionType) { return; }
        throw new InvalidOperationException("Expected " + typeof(exceptionType).Name);
    }
}
